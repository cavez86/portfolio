/** Class names for a button look, merged so callers' classes win (also for links styled as buttons). */
const buttonVariants = (props?: VariantProps<typeof variants>) => cn(variants(props));

function Button({
  className,
  variant = 'default',
  size = 'default',
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof variants>) {
  return <ButtonPrimitive className={cn(variants({ size, variant }), className)} data-slot="button" {...props} />;
}

export { Button, buttonVariants };
